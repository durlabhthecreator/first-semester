//A variable stores a data;

public class variables_datatypes {
    public static void main(String[] args) {
    int length; //Declaration
    length = 7; //Initialisation
    int breadth = 3;
    int area = length*breadth;
    System.out.print(area);
    // Here int is a datatype, length and breadth are variables and 7,3 are values.
    }
}

