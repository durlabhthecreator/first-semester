public class escape_sequences {
    public static void main(String[] args) {
      System.out.println("Hello\nWorld");
      System.out.println("Hello\tWorld");
      System.out.println("He says,\"Java is easy language\".");
      System.out.println("C:\\User");
      System.out.print("https:\\\\youtube.com");
    }
}


/*
\n  → new line
\t  → tab space
\"  → double quote
\\  → backslash
*/